  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  MX_I2C1_Init();
  MX_I2C2_Init();
  MX_USART1_UART_Init();
  MX_ADC1_Init();
  MX_TIM2_Init();
  MX_TIM4_Init();
  /* USER CODE BEGIN 2 */
  Autotune_SelectBootMode();
  if (HAL_ADCEx_Calibration_Start(&hadc1) != HAL_OK) Error_Handler();
  if (Autotune_IsEnabled()) Motor_Init();
  else {
    OLED_Init();
    Car_System_Init();
  }
  Control_StartTimer();
  if (Autotune_IsEnabled()) Autotune_Init();
  uint32_t tick_10ms = HAL_GetTick();
  uint32_t tick_100ms = tick_10ms;
  uint32_t tick_1s = tick_10ms;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    uint32_t now = HAL_GetTick();
    Serial_Poll();
    if (Autotune_IsEnabled()) {
      Autotune_Poll();
    } else {
      FSM_KeyScan();
      if (now - tick_10ms >= CONTROL_PERIOD_MS) {
        tick_10ms = now;
        FSM_ControlLoop_10ms(); /* Foreground sensors/route; PWM runs on TIM1. */
      }
      if (now - tick_100ms >= 200u) {
        tick_100ms = now;
        FSM_OLED_Update();
      }
      if (now - tick_1s >= 1000u) {
        tick_1s = now;
        FSM_Timer1s_Tick();
      }
      OLED_Poll(); /* At most one bounded 16-byte transfer per iteration. */
    }
  }
  /* USER CODE END WHILE */

  /* USER CODE BEGIN 3 */
  /* USER CODE END 3 */
